let current = 'he';
const listeners = new Set();

export function setLocale(locale) {
  if (!DICTIONARIES[locale]) return current;
  current = locale;
  for (const listener of listeners) listener(current);
  return current;
}

export function getLocale() {
  return current;
}

export function localeMeta(locale = current) {
  return LOCALES[locale] ?? LOCALES.he;
}

export function onLocaleChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/**
 * Translate a key. Values may be plain strings or functions taking params,
 * which keeps pluralisation and interpolation in the dictionary where the
 * grammar lives rather than at every call site.
 */
export function t(key, params) {
  const entry = DICTIONARIES[current]?.[key] ?? DICTIONARIES.he[key];
  if (entry === undefined) return key;
  return typeof entry === 'function' ? entry(params ?? {}) : entry;
}

/** Time strings bundled for `formatRelative`. */
export function timeStrings() {
  return {
    justNow: t('time.justNow'),
    minutesAgo: (n) => t('time.minutesAgo', n),
    hoursAgo: (n) => t('time.hoursAgo', n),
    daysAgo: (n) => t('time.daysAgo', n),
  };
}

/** Exposed for the test that asserts both dictionaries stay in sync. */
export function dictionaryKeys(locale) {
  return Object.keys(DICTIONARIES[locale] ?? {});
}
